-- 1. ENABLE ROW LEVEL SECURITY AND PERMISSIVE POLICIES FOR 'product'
ALTER TABLE public.product ENABLE ROW LEVEL SECURITY;

-- Allow everyone (anonymous customers + admin) to view products
DROP POLICY IF EXISTS "Public can view products" ON public.product;
CREATE POLICY "Public can view products" 
ON public.product FOR SELECT 
TO anon, authenticated 
USING (true);

-- Allow inserting new products
DROP POLICY IF EXISTS "Public can insert products" ON public.product;
CREATE POLICY "Public can insert products" 
ON public.product FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- Allow updating products (e.g., updating img_url, price, stock)
DROP POLICY IF EXISTS "Public can update products" ON public.product;
CREATE POLICY "Public can update products" 
ON public.product FOR UPDATE 
TO anon, authenticated 
USING (true);

-- Allow deleting products
DROP POLICY IF EXISTS "Public can delete products" ON public.product;
CREATE POLICY "Public can delete products" 
ON public.product FOR DELETE 
TO anon, authenticated 
USING (true);


